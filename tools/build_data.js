#!/usr/bin/env node
/* Builds the app data from content/:
     content/official/hsk{n}.txt   official HSK 2.0 word lists (汉字|pinyin|English) — from complete-hsk-vocabulary (MIT)
     content/curated{1,2}.js      hand-written words + real-life sentences (汉字|pinyin|ລາວ|English)
     content/lao/*.txt            Lao for the remaining official words (汉字|ລາວ|English override|pinyin override)
     content/patterns.txt         sentence patterns per level (sentence builder)
     content/dialogues.txt        dialogues & passages with comprehension questions
   Writes:
     js/data/hsk{n}.js, js/data/extra.js, audio/texts.tsv, content/review/lao_review.csv
   Usage: node tools/build_data.js [--check]   (--check: verify generated files are up to date, for CI) */
const fs = require('fs'), path = require('path');
const CORE = require('../js/core.js');
const PY = require('../js/pinyin-data.js');
const ROOT = path.join(__dirname, '..');
const rd = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const LEVELS = [1, 2, 3, 4, 5, 6];
const clean = s => String(s || '').replace(/[|`\\\r\n]/g, ' ').replace(/\s+/g, ' ').trim();

/* ---- curated (also gives the legacy v1 id map) ---- */
global.window = { HSK_RAW: {} };
require(path.join(ROOT, 'content/curated1.js')); require(path.join(ROOT, 'content/curated2.js'));
const CUR = window.HSK_RAW;
const legacy = {};
const curatedWords = new Map(); // zh -> {py, lo, en, lvl}
const sentences = {};
for (const l of LEVELS) {
  for (const kind of ['w', 's']) {
    CUR[l][kind].trim().split('\n').map(x => x.split('|').map(s => s.trim())).filter(a => a.length >= 4 && a[0])
      .forEach((a, i) => { legacy[l + kind + i] = kind + ':' + a[0]; });
  }
  CUR[l].w.trim().split('\n').map(x => x.split('|').map(s => s.trim())).filter(a => a.length >= 4 && a[0])
    .forEach(a => { if (!curatedWords.has(a[0])) curatedWords.set(a[0], { py: a[1], lo: a[2], en: a[3], lvl: l }); });
  sentences[l] = CUR[l].s.trim().split('\n').map(x => x.split('|').map(s => s.trim())).filter(a => a.length >= 4 && a[0]);
}

/* ---- Lao for official words ---- */
const lao = new Map();
for (const f of fs.readdirSync(path.join(ROOT, 'content/lao')).sort()) {
  rd('content/lao/' + f).split('\n').forEach((line, n) => {
    const a = line.split('|').map(s => s.trim());
    if (!a[0]) return;
    if (!a[1]) throw new Error(`content/lao/${f}:${n + 1} has no Lao: ${line}`);
    lao.set(a[0], { lo: a[1], en: a[2] || '', py: a[3] || '' });
  });
}

/* ---- merge ---- */
const shortEn = en => {
  let out = '';
  for (const part of en.split('; ')) { if (out && (out + '; ' + part).length > 70) break; out = out ? out + '; ' + part : part; }
  return out.length > 90 ? out.slice(0, 87) + '…' : out;
};
const words = {}, seen = new Set(), review = [];
const missing = [];
for (const l of LEVELS) {
  words[l] = [];
  for (const line of rd(`content/official/hsk${l}.txt`).split('\n')) {
    const [zh, py, en] = line.split('|');
    if (!zh || seen.has(zh)) continue;
    seen.add(zh);
    const c = curatedWords.get(zh), o = lao.get(zh);
    if (c) { words[l].push([zh, c.py, c.lo, c.en]); review.push([l, 'w', zh, c.py, c.lo, c.en, 'curated']); continue; }
    if (!o) { missing.push(`HSK${l} ${zh}`); continue; }
    const row = [zh, o.py || py, o.lo, o.en || shortEn(en)];
    words[l].push(row); review.push([l, 'w', zh, row[1], row[2], row[3], 'official']);
  }
}
// curated words that are not in the official lists stay at their curated level (useful real-life extras)
for (const [zh, c] of curatedWords) {
  if (seen.has(zh)) continue;
  seen.add(zh);
  words[c.lvl].push([zh, c.py, c.lo, c.en]);
  review.push([c.lvl, 'w', zh, c.py, c.lo, c.en, 'extra']);
}
for (const l of LEVELS) sentences[l].forEach(a => review.push([l, 's', a[0], a[1], a[2], a[3], 'sentence']));
if (missing.length) { console.error('Missing Lao for', missing.length, 'words:', missing.slice(0, 20).join(', ')); process.exit(1); }

/* ---- patterns & dialogues ---- */
const patterns = CORE.parsePatterns(rd('content/patterns.txt'));
const dialogues = CORE.parseDialogues(rd('content/dialogues.txt'));
for (const l of LEVELS) {
  if (!patterns[l] || !patterns[l].length) throw new Error('No patterns for HSK ' + l);
  patterns[l].forEach(p => p.ex.forEach(e => { if (!e.py || !e.lo || !e.en) throw new Error('Bad pattern example: ' + e.zh); }));
  (dialogues[l] || []).forEach(d => {
    d.lines.forEach(x => { if (!x.zh || !x.py || !x.lo) throw new Error('Bad dialogue line in ' + d.title + ': ' + x.zh); });
    d.qs.forEach(q => { if (q.wrong.length < 2) throw new Error('Question needs ≥2 wrong options: ' + q.q); });
  });
}

/* ---- outputs ---- */
const out = {};
const tpl = s => s.replace(/`/g, "'").replace(/\$\{/g, '$ {');
for (const l of LEVELS) {
  out[`js/data/hsk${l}.js`] = `/* GENERATED by tools/build_data.js — edit content/ instead. Format: 汉字|pinyin|ລາວ|English */
window.HSK_RAW = window.HSK_RAW || {};
window.HSK_RAW[${l}] = {
w: \`
${tpl(words[l].map(r => r.map(clean).join('|')).join('\n'))}
\`,
s: \`
${tpl(sentences[l].map(r => r.map(clean).join('|')).join('\n'))}
\`};
`;
}
out['js/data/extra.js'] = `/* GENERATED by tools/build_data.js — edit content/ instead. */
window.PATTERNS = ${JSON.stringify(patterns)};
window.DIALOGUES = ${JSON.stringify(dialogues)};
window.LEGACY_IDS = ${JSON.stringify(legacy)};
`;

// every text the app can speak → audio file name
const texts = new Set();
for (const l of LEVELS) { words[l].forEach(r => texts.add(r[0])); sentences[l].forEach(r => texts.add(r[0])); }
for (const l of LEVELS) {
  patterns[l].forEach(p => p.ex.forEach(e => texts.add(e.zh)));
  (dialogues[l] || []).forEach(d => d.lines.forEach(x => texts.add(x.zh)));
}
PY.allTexts().forEach(t => texts.add(t));
const names = new Map();
for (const t of texts) {
  const n = CORE.audioName(t);
  if (names.has(n) && names.get(n) !== t) throw new Error(`audio hash collision: ${t} / ${names.get(n)}`);
  names.set(n, t);
}
out['audio/texts.tsv'] = [...names].map(([n, t]) => `${n}\t${t}`).sort().join('\n') + '\n';

const csvq = s => /[",\n]/.test(s) ? `"${String(s).replace(/"/g, '""')}"` : String(s);
out['content/review/lao_review.csv'] = '﻿level,kind,chinese,pinyin,lao,english,source,ok(Y/N),correction\n' +
  review.map(r => r.map(csvq).join(',') + ',,').join('\n') + '\n';

const check = process.argv.includes('--check');
let stale = 0;
for (const [p, s] of Object.entries(out)) {
  const abs = path.join(ROOT, p);
  if (check) {
    if (!fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== s) { console.error('STALE:', p); stale++; }
  } else {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, s);
  }
}
const nW = LEVELS.reduce((a, l) => a + words[l].length, 0), nS = LEVELS.reduce((a, l) => a + sentences[l].length, 0);
const nP = LEVELS.reduce((a, l) => a + patterns[l].reduce((b, p) => b + p.ex.length, 0), 0);
const nD = LEVELS.reduce((a, l) => a + (dialogues[l] || []).length, 0);
console.log(`words ${nW} (${LEVELS.map(l => words[l].length).join('/')}), sentences ${nS}, pattern examples ${nP}, dialogues/passages ${nD}, audio texts ${names.size}`);
if (check && stale) { console.error(stale + ' generated file(s) out of date — run: node tools/build_data.js'); process.exit(1); }
